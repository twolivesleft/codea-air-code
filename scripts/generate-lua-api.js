// Writes Codea's API as Lua definition files for the Lua extension (LuaLS), from Codea's own
// reference: node scripts/generate-lua-api.js <codea-super checkout>
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const codea = process.argv[2];
if (!codea) {
    console.error('usage: node scripts/generate-lua-api.js <codea-super checkout>');
    process.exit(1);
}
const out = path.join(__dirname, '..', 'luals', 'api');

const KEYWORDS = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'goto', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while']);
const isName = name => /^[A-Za-z_]\w*$/.test(name || '') && !KEYWORDS.has(name);
const isPath = name => (name || '').split('.').every(isName);
const comment = text => (text || '').trim().split('\n').map(line => `--- ${line.trimEnd()}\n`).join('');
const luaType = type => {
    const t = (type || '').replace(/ or /g, '|').replace(/\s/g, '');
    return /^[A-Za-z_][\w.]*(\[\])?(\|[A-Za-z_][\w.]*(\[\])?)*\??$/.test(t) ? t : 'any';
};

function writer(header) {
    const lines = [`---@meta ${header}\n-- Generated by scripts/generate-lua-api.js from Codea's reference. Do not edit.\n`];
    const tables = new Set();
    const classes = new Set();
    return {
        lines,
        // Declares a.b.c's tables, as plain tables or as a class whose instances calling it returns
        table(name, asClass) {
            const parts = name.split('.');
            for (let i = 1; i <= parts.length; i++) {
                const table = parts.slice(0, i).join('.');
                const isClass = asClass && i === parts.length;
                if (tables.has(table) && (!isClass || classes.has(table))) { continue; }
                tables.add(table);
                if (isClass) { classes.add(table); }
                lines.push(isClass ? `---@class ${table}\n---@overload fun(...): ${table}\n${table} = {}\n` : `${table} = {}\n`);
            }
        },
    };
}

// The modern (Carbide) API, from the reference JSON Codea's editor reads
function carbide() {
    const w = writer('codea-modern');
    const params = entry => {
        let doc = '';
        const names = [];
        (entry.parameters || []).forEach((p, i) => {
            const name = isName(p.name) ? p.name : (p.name || '').includes('...') ? '...' : `p${i + 1}`;
            if (names.includes(name)) { return; }
            names.push(name);
            const optional = p.optional && name !== '...' ? '?' : '';
            doc += `---@param ${name}${optional} ${luaType(p.type)} ${(p.description || '').split('\n')[0]}\n`;
        });
        for (const r of entry.returns || []) {
            doc += `---@return ${luaType(r.type)}\n`;
        }
        return [doc, names.join(', ')];
    };
    const add = (entry, owner) => {
        if (!isName(entry.name)) { return; }
        const module = owner || entry.module;
        if (module && isPath(module)) { w.table(module); }
        const full = module ? `${module}.${entry.name}` : entry.name;
        const description = comment(entry.description || entry.helptext);
        if (entry.kind === 'function' || entry.kind === 'staticmethod') {
            const [doc, names] = params(entry);
            w.lines.push(`${description}${doc}function ${full}(${names}) end\n`);
        } else if (entry.kind === 'method' && module) {
            const [doc, names] = params(entry);
            w.lines.push(`${description}${doc}function ${module}:${entry.name}(${names}) end\n`);
        } else if (entry.kind === 'attribute' || entry.kind === 'classattribute') {
            w.lines.push(`${description}---@type ${luaType(entry.type)}\n${full} = nil\n`);
        } else if (entry.kind === 'class') {
            const name = entry.module ? `${entry.module}.${entry.name}` : entry.name;
            w.table(name, true);
            for (const member of entry.members || []) {
                add(member, name);
            }
        }
    };
    const dir = path.join(codea, 'Probe/Probe/Data/Carbide/docs/build/luadoc/api');
    for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
        for (const entry of JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))) {
            add(entry);
        }
    }
    return w.lines.join('\n');
}

// The legacy API, from the reference the Legacy tab shows
function legacy() {
    const w = writer('codea-legacy');
    const dir = path.join(codea, 'Probe/Probe/Data/Documentation');
    // "entity.add( type, ... )" or "tween(time, subject, target)": the callee and its parameters
    const signature = text => {
        const match = /^\s*(?:[\w.]+\s*=\s*)?([A-Za-z_][\w.:]*)\s*\(([^)]*)\)/.exec(text || '');
        if (!match) { return undefined; }
        const names = [];
        match[2].split(',').map(p => p.trim()).filter(Boolean).forEach((raw, i) => {
            // Some are written as their choices, such as CENTER|RADIUS
            const name = raw === '...' || isName(raw) ? raw : `p${i + 1}`;
            if (!names.includes(name)) { names.push(name); }
        });
        return { callee: match[1].replace(':', '.'), names };
    };
    for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.yaml')).sort()) {
        const chapter = yaml.load(fs.readFileSync(path.join(dir, file), 'utf8'));
        for (const entry of chapter.functions || []) {
            const description = comment(entry.description);
            const described = Object.fromEntries((entry.parameters || []).map(p => [p.name, (p.description || '').toString().split('\n')[0]]));
            const returns = entry.returns ? `---@return any ${entry.returns.toString().split('\n')[0]}\n` : '';
            if (entry.category === 'function' || entry.category === 'method') {
                const signatures = [entry.name, ...(entry.syntax || '').toString().split('\n')].map(signature).filter(Boolean);
                const seen = new Set();
                for (const { callee, names } of signatures) {
                    const key = `${callee}(${names.join(',')})`;
                    if (seen.has(key) || !isPath(callee)) { continue; }
                    seen.add(key);
                    const parts = callee.split('.');
                    if (parts.length > 1) { w.table(parts.slice(0, -1).join('.'), entry.category === 'method'); }
                    const params = names.map(n => `---@param ${n === '...' ? '...' : n} any ${n === '...' ? '' : described[n] || ''}\n`).join('');
                    const declared = entry.category === 'method' && parts.length > 1
                        ? `${parts.slice(0, -1).join('.')}:${parts[parts.length - 1]}`
                        : callee;
                    w.lines.push(`${description}${params}${returns}function ${declared}(${names.join(', ')}) end\n`);
                }
            } else if (entry.category === 'type') {
                const name = (entry.name || '').replace(/\(.*$/, '').trim();
                if (isPath(name)) { w.lines.push(description); w.table(name, true); }
            } else if (entry.category === 'const' || entry.category === 'property') {
                const name = (entry.name || '').trim();
                if (!isPath(name)) { continue; }
                const parts = name.split('.');
                if (parts.length > 1) { w.table(parts.slice(0, -1).join('.')); }
                w.lines.push(`${description}${name} = nil\n`);
            }
        }
    }
    // Defined by Codea itself rather than its reference
    w.lines.push('--- Width of the viewer, in points\n---@type number\nWIDTH = 0\n');
    w.lines.push('--- Height of the viewer, in points\n---@type number\nHEIGHT = 0\n');
    w.lines.push('--- Codea\'s assets, as keys such as asset.builtin.Planet_Cute.Character_Boy\n---@type table\nasset = {}\n');
    w.lines.push('--- Creates a class, which can inherit from base\n---@param base? table\n---@return table\nfunction class(base) end\n');
    return w.lines.join('\n');
}

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'modern.lua'), carbide());
fs.writeFileSync(path.join(out, 'legacy.lua'), legacy());
for (const file of ['modern.lua', 'legacy.lua']) {
    console.log(`${file}: ${fs.readFileSync(path.join(out, file), 'utf8').split('\n').length} lines`);
}
